"""#219 — scene-reference privacy filter (no foreign players' canonical ids).

Contract under test (#219, §70 reference collection in _generate_asset):
- scene assets carry character_id NULL, so the R1 ownership guard (#193)
  cannot run on their payload — the scene-reference loop itself must never
  expose another player's canonical portrait asset id (a character with
  user_id set that is not the requesting player's own character) via
  scene_descriptor.references or the prompt fragment
  "reference portraits: [...]".
- Included as references: NPC characters (user_id IS NULL) and the
  descriptor's player part (the requesting player's own character).
- A character row missing from the DB is fail-closed (no reference).
- All-NPC scenes keep byte-identical references/prompt behavior (leg (c) is
  a regression pin: it passes on base too — it pins the NPC path the filter
  must not over-prune).

History: #193 closed the direct read leak (foreign canonical 404), but a
scene generated by any authenticated user at a shared location still carried
every co-located player's canonical portrait id in references + prompt.
#219 closes that residual disclosure (same family as #214/#215).

RED discipline: legs (a), (b), (d) FAIL on base 81aca5ab with the foreign
canonical id visible in the observed payload (leak proof); they pass only
with the #219 filter in place.
"""
