from app.world.seed_world import seed_world  # noqa: E402

SETTINGS = None
PW = "Correct-Horse-9!"


def setup_module(module):
    global SETTINGS
    SETTINGS = load_config("config/default.yaml")


def _make_settings(tmp_path):
    visual = SETTINGS.visual.model_copy(update={
        "enabled": True,
        "storage_dir": str(tmp_path / "assets"),
        "image_size": "8x8",
    })
    return SETTINGS.model_copy(update={
        "persistence": SETTINGS.persistence.model_copy(
            update={"db_path": str(tmp_path / "w219.db")}
        ),
        "visual": visual,
    })


def _register_and_login(client, username):
    r = client.post("/auth/register", json={
        "username": username, "email": f"{username}@x.com",
        "password": PW, "age_confirmed": True,
    })
    assert r.status_code == 201, r.text
    r = client.post("/auth/login", json={"username": username, "password": PW})
    assert r.status_code == 200, r.text


def _create_character(client, name):
    r = client.post("/characters", json={"name": name, "sex": "F", "age": 30})
    assert r.status_code == 201, r.text
    return r.json()["id"]


def _build(tmp_path):
    from sqlalchemy.orm import sessionmaker

    from app.api.app import create_app
    from app.characters.generator import generate_population

    settings = _make_settings(tmp_path)
    engine = create_engine_factory(settings)
    with sessionmaker(bind=engine)() as session:
        bootstrap(engine, settings, seed=42)
        seed_world(session, settings, settings.world.world_id)
        generate_population(
            session, settings, random.Random(42),
            settings.world.world_id, 20,
        )
        session.commit()
    factory = sessionmaker(bind=engine, expire_on_commit=False)
    app = create_app(settings, factory)
    owner = TestClient(app)
    _register_and_login(owner, "w219owner")
    return settings, engine, factory, owner


def _make_canonical(client, cid):
    """Generate + promote one portrait for the caller's own character."""
    r = client.post(f"/visual/portraits/{cid}")
    assert r.status_code == 201, r.text
    asset_id = r.json()["asset"]["id"]
    r = client.post(f"/visual/assets/{asset_id}/canonical", json={"canonical": True})
    assert r.status_code == 200, r.text
    assert r.json()["canonical"] is True, r.text
    return asset_id


def _npc_canonical(client, npc_cid):
    """#191 lazy canonical generation for an NPC (any auth user may trigger)."""
    r = client.get(f"/visual/characters/{npc_cid}/portrait")
    assert r.status_code == 200, r.text
    assert r.json()["canonical"] is True, r.text
    return r.json()["id"]


def _move_to(settings, engine, loc_id, *cids):
    """Move the given characters to loc_id (co-location for scene setup)."""
    from sqlalchemy.orm import sessionmaker

    with sessionmaker(bind=engine, expire_on_commit=False)() as session:
        for cid in cids:
            session.get(Character, cid).location_id = loc_id
        session.commit()


def _npc_ids_at(settings, engine, loc_id, count):
    """Return `count` alive NPC ids (user_id NULL), co-located at loc_id."""
    from sqlalchemy.orm import sessionmaker

    with sessionmaker(bind=engine, expire_on_commit=False)() as session:
        npcs = (
            session.query(Character)
            .filter_by(
                world_id=settings.world.world_id, user_id=None, alive=True)
            .order_by(Character.id)
            .limit(count)
            .all()
        )
        assert len(npcs) == count, f"need {count} alive NPCs"
        for npc in npcs:
            npc.location_id = loc_id
        session.commit()
        return [npc.id for npc in npcs]


def _expected_refs(settings, engine, player_cid):
    """Spec-derived expectation: canonical ids of NPCs + the player's own
    character, ordered by Character.id (the §70 collection order)."""
    from sqlalchemy.orm import sessionmaker

    with sessionmaker(bind=engine)() as session:
        rows = (
            session.query(VisualAsset.id, Character.user_id, Character.id)
            .join(Character, Character.id == VisualAsset.character_id)
            .filter(
                VisualAsset.world_id == settings.world.world_id,
                VisualAsset.asset_type == "portrait",
                VisualAsset.canonical.is_(True),
                Character.alive.is_(True),
            )
            .order_by(Character.id)
            .all()
        )
        return [
            asset_id
            for asset_id, user_id, cid in rows
            if user_id is None or cid == player_cid
        ]


def _owner_location(engine, owner_cid):
    from sqlalchemy.orm import sessionmaker

    with sessionmaker(bind=engine)() as session:
        return session.get(Character, owner_cid).location_id


def _ref_fragment(prompt):
    """Extract the "reference portraits: [...]" chunk (or "" if absent)."""
    start = prompt.find("reference portraits:")
    if start < 0:
        return ""
    tail = prompt[start:]
    end = tail.find("]")
    return tail[: end + 1] if end >= 0 else tail


class TestSceneReferencePrivacy:
    def test_a_references_exclude_foreign_players(self, tmp_path):
        """(a) NPC + foreign player co-located with the caller, all with
        canonical portraits → references contain ONLY the NPC's and the
        caller's own canonical ids."""
        settings, engine, _, owner = _build(tmp_path)
        owner_cid = _create_character(owner, "Хозяйка")
        other = TestClient(owner.app)
        _register_and_login(other, "w219foreign")
        foreign_cid = _create_character(other, "Чужак")

        loc = _owner_location(engine, owner_cid)
        _move_to(settings, engine, loc, foreign_cid)
        npc_ids = _npc_ids_at(settings, engine, loc, 1)
        npc_id = npc_ids[0]

        my_id = _make_canonical(owner, owner_cid)
        foreign_id = _make_canonical(other, foreign_cid)
        npc_asset_id = _npc_canonical(owner, npc_id)

        r = owner.post("/visual/scenes", json={"location_id": loc})
        assert r.status_code == 201, r.text
        d = r.json()["asset"]["scene_descriptor"]
        expected = _expected_refs(settings, engine, owner_cid)
        assert d["player"]["id"] == owner_cid, "caller part intact"
        assert d["references"] == expected, (
            f"leak check: expected only allowed refs {expected}, "
            f"got {d['references']} (foreign canonical id {foreign_id} "
            f"must not ride a scene the owner reads)"
        )
        assert foreign_id not in d["references"]
        assert my_id in d["references"]
        assert npc_asset_id in d["references"]

    def test_b_prompt_carries_only_allowed_ids(self, tmp_path):
        """(b) the prompt fragment "reference portraits: [...]" carries only
        the allowed ids; the foreign canonical id is absent from the bytes."""
        settings, engine, _, owner = _build(tmp_path)
        owner_cid = _create_character(owner, "Хозяин")
        other = TestClient(owner.app)
        _register_and_login(other, "w219foreignb")
        foreign_cid = _create_character(other, "Гость")

        loc = _owner_location(engine, owner_cid)
        _move_to(settings, engine, loc, foreign_cid)
        npc_id = _npc_ids_at(settings, engine, loc, 1)[0]

        my_id = _make_canonical(owner, owner_cid)
        foreign_id = _make_canonical(other, foreign_cid)
        npc_asset_id = _npc_canonical(owner, npc_id)

        r = owner.post("/visual/scenes", json={"location_id": loc})
        assert r.status_code == 201, r.text
        prompt = r.json()["asset"]["prompt"]
        expected = _expected_refs(settings, engine, owner_cid)
        frag = _ref_fragment(prompt)
        assert str(foreign_id) not in frag, (
            f"leak: foreign canonical id {foreign_id} is quoted in the "
            f"scene prompt reference fragment served to the owner: {frag!r}"
        )
        assert f"reference portraits: {expected}" in prompt, (
            f"prompt fragment must carry exactly the allowed ids {expected}; "
            f"fragment: {frag!r}"
        )
        assert str(my_id) in frag
        assert str(npc_asset_id) in frag

    def test_c_all_npc_scene_references_unchanged(self, tmp_path):
        """(c) all-NPC scene (caller has no character): both NPC canonicals
        are collected as before — the filter must not over-prune."""
        settings, engine, _, user = _build(tmp_path)
        _register_and_login(user, "w219npcviewer")

        # Two alive NPCs co-located at the first NPC's location, each with a
        # canonical portrait (real #191 lazy-generation path).
        from sqlalchemy.orm import sessionmaker

        with sessionmaker(bind=engine)() as session:
            npcs = (
                session.query(Character)
                .filter_by(
                    world_id=settings.world.world_id, user_id=None, alive=True)
                .order_by(Character.id)
                .limit(2)
                .all()
            )
            assert len(npcs) == 2
            loc = npcs[0].location_id
            npc1_id, npc2_id = npcs[0].id, npcs[1].id
            npcs[1].location_id = loc
            session.commit()

        npc1 = _npc_canonical(user, npc1_id)
        npc2 = _npc_canonical(user, npc2_id)

        r = user.post("/visual/scenes", json={"location_id": loc})
        assert r.status_code == 201, r.text
        scene = r.json()["asset"]
        d = scene["scene_descriptor"]
        assert d["player"] is None, "no character → no player part"
        expected = _expected_refs(settings, engine, None)
        assert npc1 in expected and npc2 in expected
        assert d["references"] == expected, (
            f"NPC references must be collected unchanged; expected "
            f"{expected}, got {d['references']}"
        )
        assert f"reference portraits: {expected}" in scene["prompt"]

    def test_d_only_caller_when_foreign_player_present(self, tmp_path):
        """(d) caller + foreign player co-located (no NPC canonicals):
        references are exactly [caller's canonical id] — the foreign id is
        absent from references and prompt."""
        settings, engine, _, owner = _build(tmp_path)
        owner_cid = _create_character(owner, "Дома")
        other = TestClient(owner.app)
        _register_and_login(other, "w219foreignd")
        foreign_cid = _create_character(other, "Пришелец")

        loc = _owner_location(engine, owner_cid)
        _move_to(settings, engine, loc, foreign_cid)

        my_id = _make_canonical(owner, owner_cid)
        foreign_id = _make_canonical(other, foreign_cid)

        r = owner.post("/visual/scenes", json={"location_id": loc})
        assert r.status_code == 201, r.text
        scene = r.json()["asset"]
        d = scene["scene_descriptor"]
        assert d["references"] == [my_id], (
            f"leak check: expected only the caller's canonical [{my_id}], "
            f"got {d['references']} (foreign canonical id {foreign_id} "
            f"must not ride a scene the owner reads)"
        )
        assert str(foreign_id) not in _ref_fragment(scene["prompt"])
        assert f"reference portraits: [{my_id}]" in scene["prompt"]
